"""Write launcher-lite/icon-map.js from the TV's own app list.

Samsung's Home draws each store app's artwork from
/opt/share/webappservice/apps_icon/all/<store ID>/304x304.png. A web app can read those
files but cannot learn which store ID belongs to which app, so this tool reads that
mapping from the TV (via `aerotizen apps`) and ships it with Lite.

Run before installing Lite, and again after installing new apps:

    python tools/lite_icon_map.py --tv 192.168.1.71
    aerotizen --tv 192.168.1.71 install ./launcher-lite
"""

import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "launcher-lite" / "icon-map.js"
CONFIG = Path.home() / ".config" / "aerotizen"
FIELD = re.compile(r"^-+(\w+)\s*=(.*?)-+\s*$")
ART_DIR = re.compile(r"/apps_icon/all/([^/]+)/?$")


def latest_snapshot(host):
    snapshots = sorted(CONFIG.glob(f"{host}-applist-*.txt"))
    if not snapshots:
        raise SystemExit(f"No app list snapshot for {host} in {CONFIG}")
    return snapshots[-1]


def parse(text):
    """Map app_tizen_id -> artwork folder name. Fields of one app precede its app_tizen_id."""
    mapping, current = {}, {}
    for line in text.splitlines():
        match = FIELD.match(line.strip())
        if not match:
            continue
        key, value = match.group(1), match.group(2).strip()
        current[key] = value
        if key == "app_tizen_id":
            art = ART_DIR.search(current.get("app_panel_icon_path", ""))
            if art and art.group(1) != value:  # a folder named after the app ID is not artwork
                mapping[value] = art.group(1)
            current = {}
    return mapping


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tv", required=True, help="TV IP address")
    parser.add_argument("--no-fetch", action="store_true", help="use the newest saved snapshot")
    args = parser.parse_args()
    if not args.no_fetch:
        subprocess.run(["aerotizen", "--tv", args.tv, "apps"], check=True, stdout=subprocess.DEVNULL)
    snapshot = latest_snapshot(args.tv)
    mapping = parse(snapshot.read_text(errors="replace"))
    body = json.dumps(dict(sorted(mapping.items())), indent=2)
    OUTPUT.write_text(
        "// Generated by tools/lite_icon_map.py from the TV's app list. Do not edit.\n"
        "// App ID -> folder under /opt/share/webappservice/apps_icon/all/ holding Samsung's artwork.\n"
        f"window.LITE_ICON_MAP = {body};\n"
    )
    print(f"{OUTPUT.relative_to(ROOT)}: {len(mapping)} apps from {snapshot.name}")


if __name__ == "__main__":
    main()
